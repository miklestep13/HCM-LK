/** Участник (виджет «Участники»): сообщество, цель, мероприятие */
export interface Member {
  /** ФИО */
  n: string;
  /** должность */
  pos: string;
  /** подразделение */
  dep?: string;
  /** портрет: номер av1–av8 или класс */
  av: number | string;
  role?: string;
  /** вес, % */
  w?: number | string | null;
  /** нельзя изменить или убрать (например, исполнитель цели) */
  lock?: boolean;
  /** группа вместо сотрудника: подразделение, команда или компания (в pos — «Подразделение · 24 сотрудника») */
  kind?: 'dep' | 'team' | 'company';
  /** сотрудников в группе */
  cnt?: number;
}

/** Что показывать о участнике */
export type MemberField = 'av' | 'name' | 'pos' | 'role' | 'w';
/** Ввод: none — только просмотр, inline — правка прямо в списке, drawer — добавление и правка в сайдбаре */
export type MemberEdit = 'none' | 'inline' | 'drawer';
/** Вывод: карточки, таблица или оба вида с переключателем в шапке */
export type MemberView = 'cards' | 'table' | 'both';

/** Участник события (widgets/event-members): сотрудник, тип и роль, период участия, описание, признаки */
export interface EvMember {
  id: string;
  /** ФИО (пусто — новая строка, сотрудник еще не выбран) */
  n: string;
  pos: string;
  dep?: string;
  av: number | string;
  /** тип участника — из реестра (по виду: сотрудник, подразделение, команда, компания), в виджете не правится */
  type: string;
  /** вид участника: пусто — сотрудник; подразделение, команда, компания */
  kind?: 'dep' | 'team' | 'company';
  /** роли участника (может быть несколько): организатор, ведущий, участник… */
  roles: string[];
  /** период участия: «дд.мм.гггг»; без даты окончания — бессрочно */
  from: string;
  to?: string;
  desc?: string;
  /** вес участника, % */
  w?: number | null;
  /** статус, заданный вручную; пусто — по датам участия */
  st?: string;
  /** признак: основной участник */
  main?: boolean;
}

/** колонки виджета «Участники события» (любую можно отключить) */
export type EvCol = 'flags' | 'member' | 'type' | 'role' | 'w' | 'from' | 'to' | 'desc' | 'status';
