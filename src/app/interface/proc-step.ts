/** Шаг процесса (виджет «Ход процесса», widgets/proc-steps): название, подпись под ним и состояние */
export interface ProcStep {
  /** название этапа */
  n: string;
  /** подпись под названием: дата, ответственный, срок */
  sub?: string;
  /** done — пройден (зеленый, галочка); cur — текущий (синий); next — впереди (серый); fail — отклонен (красный, крестик); stop — остановлен (серый, отозвано) */
  st: 'done' | 'cur' | 'next' | 'fail' | 'stop';
}
