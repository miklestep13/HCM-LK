/** Начисление сотруднику: зарплата, аванс, премия */
export interface IncomeOp {
  kind: 'Зарплата' | 'Аванс' | 'Премия';
  /** месяц и год, за которые начислено: «октябрь 2026» */
  period: string;
  /** дата выплаты «05.11.2026» */
  paid: string;
  /** сумма, ₽ */
  amt: number;
}

/** Блок «Доход»: ежемесячный доход и последние начисления */
export interface Income {
  /** ежемесячный доход, ₽ */
  monthly: number;
  /** подпись под суммой */
  note: string;
  /** последние начисления, новые сверху */
  ops: IncomeOp[];
}
