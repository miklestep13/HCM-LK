/** Сотрудник в таблице заявок: ФИО, должность, аватар (класс av1–av8; 'me' — фото текущего пользователя) */
export interface ReqPerson {
  n: string;
  pos: string;
  av: string;
}

/** Вкладка списка заявок: мои, требуют действия, наблюдаю */
export type ReqTab = 'my' | 'act' | 'watch';

/** Заявка сотрудника («Мой кабинет → Заявки») */
export interface Req {
  /** номер: REQ-4830 */
  id: string;
  /** название */
  n: string;
  /** категория каталога заявок */
  cat: string;
  /** статус: Черновик, Зарегистрирована, На согласовании, В работе, На доработке, Выполнена, Отклонена, Отозвана */
  st: string;
  /** текущий этап, его номер и число этапов */
  stage: string;
  step: number;
  steps: number;
  /** срок по этапу: «дд.мм.гггг чч:мм» (у завершенных — пусто) */
  due?: string;
  /** автор — кто создал заявку */
  ini: ReqPerson;
  /** заявитель — от чьего имени заявка (если не автор) */
  app?: ReqPerson;
  /** ответственный за этап (у завершенных — пусто) */
  resp?: ReqPerson;
  /** создано и завершено: «дд.мм.гггг чч:мм» */
  created: string;
  closed?: string;
  /** оценка исполнения 1–5 (только у выполненных) */
  rate?: number;
  tab: ReqTab;
  /** описание (форма «Новая заявка») */
  info?: string;
  /** наименование и подразделение (форма «Новая заявка») */
  title?: string;
  dep?: string;
}

/** Быстрая заявка над списком: иконка, название, подсказка, группа каталога */
export interface ReqQuick {
  icon: string;
  n: string;
  d: string;
  grp: string;
}
