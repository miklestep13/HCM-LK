import { AttachFile } from './attach';
import { EvMember } from './member';
/** Сотрудник в таблице заявок: ФИО, должность, аватар (класс av1–av8; 'me' — фото текущего пользователя) */
export interface ReqPerson {
  n: string;
  pos: string;
  av: string;
}

/** Вкладка списка заявок: мои, требуют действия, наблюдаю */
export type ReqTab = 'my' | 'act' | 'watch';

/** Заявка сотрудника («Мой кабинет → Заявки») */
export interface Req {
  /** номер: REQ-4830 */
  id: string;
  /** название */
  n: string;
  /** категория каталога заявок */
  cat: string;
  /** статус: Черновик, Зарегистрирована, На согласовании, В работе, На доработке, Выполнена, Отклонена, Отозвана */
  st: string;
  /** текущий этап, его номер и число этапов */
  stage: string;
  step: number;
  steps: number;
  /** срок по этапу: «дд.мм.гггг чч:мм» (у завершенных — пусто) */
  due?: string;
  /** автор — кто создал заявку */
  ini: ReqPerson;
  /** заявитель — от чьего имени заявка (если не автор) */
  app?: ReqPerson;
  /** ответственный за этап (у завершенных — пусто) */
  resp?: ReqPerson;
  /** создано и завершено: «дд.мм.гггг чч:мм» */
  created: string;
  closed?: string;
  /** оценка исполнения 1–5 (только у выполненных) */
  rate?: number;
  tab: ReqTab;
  /** описание (форма «Добавление заявки») */
  info?: string;
  /** наименование и подразделение (форма «Добавление заявки») */
  title?: string;
  dep?: string;
  /** код, тип канала поступления, дата завершения обработки и связанные документы (форма «Добавление заявки») */
  code?: string;
  /** тип канала поступления: портал, мобильное приложение, почта, телефон, лично */
  chan?: string;
  procEnd?: string;
  docs?: AttachFile[];
  /** «Дата с» и «Дата по» из формы (нет — дата создания и срок) */
  from?: string;
  to?: string;
  /** участники заявки (кроме автора, заявителя и ответственного — они берутся из полей): участник и роль */
  members?: EvMember[];
  /** названия этапов процесса (нет — по категории заявки) */
  stages?: string[];
  /** результат обработки (заполняет ответственный) */
  res?: ReqRes;
}

/** результат обработки заявки: вид, комментарий (при отказе — причина отказа), документы, когда и кто */
export interface ReqRes {
  kind: string;
  text: string;
  docs?: AttachFile[];
  date: string;
  by?: string;
}

/** Тип в каталоге «Добавление заявки»: иконка, название, краткое описание, группа */
export interface ReqPick {
  icon: string;
  n: string;
  d: string;
  cat: string;
}

/** поле формы «Добавление заявки», которое зависит от типа заявки (номер, дата создания и состояние есть всегда) */
export type ReqFieldKey = 'code' | 'name' | 'from' | 'to' | 'procEnd' | 'chan' | 'dep' | 'text';

/** поле формы для типа заявки: подпись, обязательность, ширина (2 — две колонки из четырех, 4 — вся строка) */
export interface ReqFormField {
  k: ReqFieldKey;
  l: string;
  req?: boolean;
  w?: 1 | 2 | 4;
}

/** тип заявки в справочнике «Управление персоналом → Заявки → Типы заявок»: название, когда создан и изменен */
export interface ReqTypeItem {
  id: string;
  n: string;
  /** «дд.мм.гггг, чч:мм» */
  created: string;
  changed: string;
}
