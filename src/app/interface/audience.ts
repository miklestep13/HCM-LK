/**
 * Условия отбора участников (widgets/audience).
 * Группа — условия через «И»; группы — через «ИЛИ». Условие — поле, «включает / исключает» и несколько значений (между ними — «ИЛИ»).
 * Пример: (Подразделение включает «Риски», «Продукты» И Грейд исключает «Стажер») ИЛИ (Должность включает «Руководитель отдела продаж»).
 */
export type AudOp = 'in' | 'out';

export interface AudCond {
  /** поле: «Подразделение», «Должность», «Локация»… */
  f: string;
  op: AudOp;
  /** значения — подходит любое из них */
  v: string[];
}

export interface AudGroup {
  c: AudCond[];
}
