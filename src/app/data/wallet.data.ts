/** Отправитель / получатель операции: название, аватар (класс .av или значок организации), направление */
export interface WalletParty {
  name: string;
  av: string;
  org: '' | 'bank' | 'shop';
  dir: 'in' | 'out';
}
export function walletParty(h: WalletOp): WalletParty {
  const dir = h.amt > 0 ? 'in' : 'out', w = h.who || '';
  if (/^Корпоративный магазин/.test(w)) return { name: 'Корпоративный магазин', av: '', org: 'shop', dir };
  if (w === 'Компания') return { name: 'Меридиан Банк', av: '', org: 'bank', dir };
  const name = w.replace(/^(От|Кому):\s*/, '').replace(/ · .*$/, '');
  const e = WALLET_EMPLOYEES.find((x) => x.name === name);
  return { name, av: 'av' + (e ? e.av : 1), org: '', dir };
}
