/** Карточка каталога по id курса или мероприятия */
export function cpLearnItem(id: string): CtLearnItem | null {
  const c = LEARN_CATALOG.crs.find((x) => x.id === id);
  if (c) return { id: c.id, kind: 'crs', title: c.title, type: 'Курс', grade: (c.grd || '').replace(' специалист', ''), section: c.sph || '', tag: c.tag || '', img: c.img, line: c.dur || '' };
  const e = LEARN_CATALOG.ev.find((x) => x.id === id);
  if (e) return { id: e.id, kind: 'ev', title: e.title, type: 'Мероприятие', grade: (e.grd || '').replace(' специалист', ''), section: e.sph || '', tag: e.tag || '', img: e.img, line: e.line || '' };
  return null;
}
