/** Атрибуты способа развития для карточки HR: тип, длительность и грейд. Сроки назначения сотрудника сюда не входят. */
export function ctWayFacts(w: CpWay, grades: string[]): { icon: string; text: string }[] {
  const out: { icon: string; text: string }[] = [{ icon: '', text: WAY_KIND[w.icon] }];
  const time = w.meta.find((m) => m.icon === 'clock' && /\d/.test(m.text));
  if (time) out.push({ icon: 'clock', text: time.text });
  const list = grades.length ? w.grades.filter((g) => grades.includes(g)) : w.grades;
  for (const g of list) out.push({ icon: 'grade', text: g });
  return out;
}

