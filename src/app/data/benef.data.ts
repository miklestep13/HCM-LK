/** формат суммы бланка: «190 000,00 ₽» */
export function slipAmt(n: number): string {
  const [a, b] = Math.abs(n).toFixed(2).split('.');
  return (n < 0 ? '−' : '') + a.replace(/\B(?=(\d{3})+(?!\d))/g, '\u00a0') + ',' + b + '\u00a0₽';
}

