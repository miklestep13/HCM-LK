/** n человек со сдвигом off; pref — сначала люди этого подразделения (pplList прототипа) */
export function pplList(n: number, off = 0, pref?: string): Person[] {
  const out: Person[] = [];
  for (let k = 0; k < Math.min(n, PEOPLE.length); k++) out.push(PEOPLE[(k + off) % PEOPLE.length]);
  if (pref) {
    const all = PEOPLE.filter((p) => p[2] === pref);
    return all.concat(out.filter((p) => !all.includes(p))).slice(0, out.length);
  }
  return out;
}

