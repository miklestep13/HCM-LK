function toLearn(c: { id: string; title: string; img: string; grd?: string; sph?: string; tag?: string; dur?: string; line?: string }): CtLearnItem {
  const ev = !c.dur;
  return {
    id: c.id,
    kind: ev ? 'ev' : 'crs',
    title: c.title,
    type: ev ? 'Мероприятие' : 'Курс',
    grade: (c.grd || '').replace(' специалист', ''),
    section: c.sph || '',
    tag: c.tag || '',
    img: c.img,
    line: c.dur || c.line || '',
  };
}
