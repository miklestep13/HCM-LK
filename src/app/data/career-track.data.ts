/** «Сегодня» прототипа: срок действия сверяем с этой датой */
const CT_TODAY = 20260930;
/** Одна позиция, без лестницы Специалист → Главный */
const CT_NO_GRADE = new Set(['r24', 'r25', 'r26', 'r27']);

/** Срок действия должности. Пустое «по» — бессрочно. Часть справочника уже закрыта на 30.09.2026. */
export function ctTerm(id: string): { from: string; to: string } {
  const n = Number(id.replace(/\D/g, '')) || 1;
  if (n === 7 || n === 14 || n === 20 || n === 21) return { from: '01.01.2023', to: '31.12.2025' };
  const fromList = ['01.01.2024', '01.04.2024', '01.09.2024', '01.01.2025', '01.06.2025', '01.09.2025', '01.01.2026', '01.03.2026'];
  return { from: fromList[n % fromList.length], to: n % 5 === 0 ? '31.12.2026' : '' };
}

export function ctNoGrade(id: string): boolean {
  return CT_NO_GRADE.has(id);
}

/** Действует, если «сегодня» попадает в срок. Пустое «по» срок не закрывает. */
export function ctActs(from: string, to: string): 'Действует' | 'Не действует' {
  const f = ctYmd(from);
  const t = ctYmd(to);
  if (f && f > CT_TODAY) return 'Не действует';
  if (t && t < CT_TODAY) return 'Не действует';
  return 'Действует';
}

export function ctYmd(d: string): number {
  const m = /(\d{2})\.(\d{2})\.(\d{4})/.exec(d || '');
  return m ? Number(m[3] + m[2] + m[1]) : 0;
}

