/** Что сотрудник умеет на этом уровне компетенции. Для шаблона — тексты ее страницы */
export function ctBehavior(comp: string, level: string): string {
  if (!level) return '';
  if (comp === 'Кредитный анализ и оценка рисков') return CT_COMP_LEVELS[level].join('. ') + '.';
  const i = CT_LEVELS.indexOf(level);
  return CT_IND[comp]?.[i] || CT_LEVEL_DESC[level] || '';
}

export function ctCompId(name: string): string {
  return CT_COMPS.find((c) => c.name === name)?.id || CT_TPL_COMP;
}

/** Курсы и мероприятия каталога: для роли — кредитование, розница, комплаенс и два цифровых курса; для компетенции — кредитование */
export function ctLearn(scope: 'role' | 'comp'): CtLearnItem[] {
  const items = [...LEARN_CATALOG.crs, ...LEARN_CATALOG.ev]
    .filter((c) => !/HR/.test(c.role || '') && !/HR/.test(c.sph || '') && /Розничный бизнес|Всем/.test(c.role || ''))
    .map((c) => toLearn(c));
  if (scope === 'comp') return items.filter((x) => /Кредитование/.test(x.section));
  return items.filter((x) => /Кредитование|Розничные продукты|Риски и комплаенс/.test(x.section) || x.id === 'c2' || x.id === 'c4');
}

export function ctSort<T>(rows: T[], pick: (row: T) => string | number, dir: 1 | -1): T[] {
  return [...rows].sort((a, b) => {
    const x = pick(a), y = pick(b);
    return (x < y ? -1 : x > y ? 1 : 0) * dir;
  });
}

export function ctPlural(n: number, one: string, few: string, many: string): string {
  const m = n % 10, h = n % 100;
  return m === 1 && h !== 11 ? one : m >= 2 && m <= 4 && (h < 12 || h > 14) ? few : many;
}

