/** Неразрывный пробел после короткого предлога и союза. */
function t(s: string): string {
  return s.replace(/(^|[\s«(])(в|во|с|со|к|ко|на|по|о|об|до|из|от|за|не|и|а|у)\s/gi, '$1$2\u00A0');
}

function art(p: {
  id: string;
  title: string;
  lead: string;
  tags?: string[];
  date: string;
  time?: string;
  img?: string;
  lk?: number;
  cm?: number;
  vw?: number;
  authorFio?: string;
  cmAu?: string;
  cmAv?: number;
  body: NewsBodyBlock[];
}): NewsPost {
  return {
    id: p.id,
    cat: 'Компания',
    title: t(p.title),
    lead: t(p.lead),
    tags: p.tags ?? [],
    date: p.date,
    time: p.time ?? '10:00',
    cm: p.cm ?? 4,
    vw: p.vw ?? 180,
    lk: p.lk ?? 16,
    author: 0,
    authorFio: p.authorFio ?? 'Меридиан Банк',
    chat: [],
    img: p.img,
    cmAu: p.cmAu,
    cmAv: p.cmAv,
    body: p.body.map((b) => (b[0] !== 'img' && typeof b[1] === 'string' ? [b[0], t(b[1])] : b)),
  };
}

